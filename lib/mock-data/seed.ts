function emp(
  id: string,
  employeeCode: string,
  firstName: string,
  lastName: string,
  position: string,
  department: string,
  phone: string,
  projectId: string | null,
  status: AdminState["employees"][number]["status"],
  hiredAt: string,
): AdminState["employees"][number] {
  const email = `${firstName}.${lastName}@staff.cpmis.demo`.toLowerCase();
  return { id, employeeCode, firstName, lastName, position, department, phone, email, projectId, status, hiredAt };
}

function task(
  id: string,
  title: string,
  projectId: string,
  assignee: string,
  dueDate: string,
  priority: AdminState["tasks"][number]["priority"],
  status: AdminState["tasks"][number]["status"],
): AdminState["tasks"][number] {
  return { id, title, projectId, assignee, dueDate, priority, status };
}

function note(
  id: string,
  type: AdminState["notifications"][number]["type"],
  title: string,
  message: string,
  read: boolean,
  createdAt: string,
): AdminState["notifications"][number] {
  return { id, type, title, message, read, createdAt };
}

function log(
  id: string,
  userId: string,
  userName: string,
  action: string,
  module: string,
  record: string,
  status: AdminState["activityLogs"][number]["status"],
  timestamp: string,
): AdminState["activityLogs"][number] {
  return { id, userId, userName, action, module, record, status, timestamp };
}
